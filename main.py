# які tdd-тести порадиш написати для такого завдання:
# 1. Генеруємо 100 чисел від 1 до 100.
# 2. Перемішуємо їх у випадковому порядку.
# 3. Виводимо їх на екран.


# В яких випадках ефективніше підключати імпорти всередині визначення певної ф-ції?
# Підключати імпорти всередині визначення певної функції може бути ефективніше в наступних випадках:
# 1. Коли імпорт потрібен лише для конкретної функції: Якщо імпорт використовується лише в одній функції,
# розміщення його всередині цієї функції може допомогти зменшити час завантаження модуля,
# оскільки імпорт буде виконуватися лише тоді, коли функція буде викликана.
# 2. Коли імпорт залежить від умов: Якщо імпорт потрібен лише за певних умов
# (наприклад, залежно від параметрів функції), розміщення імпорту всередині функції дозволяє
# уникнути непотрібного імпорту, якщо ці умови не виконуються.
# 3. Коли імпорт може викликати конфлікти: Якщо імпорт може викликати конфлікти з іншими частинами коду
# або якщо імпортовані модулі мають однакові імена, розміщення імпорту всередині функції може допомогти
# уникнути таких конфліктів.
# 4. Коли імпорт може бути дорогим: Якщо імпортований модуль є великим або має багато залежностей,
# розміщення імпорту всередині функції може допомогти зменшити час завантаження модуля,
# оскільки імпорт буде виконуватися лише тоді, коли функція буде викликана.    

# А якщо цю функцію буде викликано 1 млн разів,
# то ефективніше буде розмістити імпорт на початку модуля,
# щоб уникнути повторного імпорту при кожному виклику функції.
# Це дозволить зменшити час виконання функції,
# оскільки імпорт буде виконуватися лише один раз при завантаженні модуля,
# а не при кожному виклику функції.
# У випадку, коли функція викликається багато разів,
# розміщення імпорту на початку модуля є більш ефективним,
# оскільки це дозволяє уникнути повторного імпорту при кожному виклику функції,
# що може значно знизити час виконання функції.     

# А якщо імпортований модуль є великим або має багато залежностей, й  цю функцію буде викликано 1 млн разів,
# то ефективніше буде розмістити імпорт на початку модуля,
# щоб уникнути повторного імпорту при кожному виклику функції.
# Це дозволить зменшити час виконання функції,
# оскільки імпорт буде виконуватися лише один раз при завантаженні модуля,
# а не при кожному виклику функції.
# У випадку, коли функція викликається багато разів,
# розміщення імпорту на початку модуля є більш ефективним,
# оскільки це дозволяє уникнути повторного імпорту при кожному виклику функції,
# що може значно знизити час виконання функції.     



def generate_100_numbers() -> list:
    return list(range(1, 101))


def sort_randomly(numbers: list) -> list:
    import random
    random.shuffle(numbers)
    return numbers


def create_dict(shuffled_list: list) -> dict:
    return {i: num for i, num in enumerate(shuffled_list)}


def main() -> None:
    new_list = generate_100_numbers()
    print(f'Генеруємо 100 чисел від 1 до 100: {new_list}')
    shuffled_list = sort_randomly(new_list)
    print(f'Перемішуємо їх у випадковому порядку: {shuffled_list}')
    result_dict = create_dict(shuffled_list)
    print(f'Створюємо словник: {result_dict}')


if __name__ == '__main__':
    main()